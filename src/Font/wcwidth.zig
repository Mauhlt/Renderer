fn inTable(table: []const Range, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (cp < table[mid].lo) {
            hi = mid;
        } else if (cp > table[mid].hi) {
            lo = mid + 1;
        } else return true;
    }
    return false;
}

/// Cells occupied by `cp`. Callers handle C0/C1 controls before asking.
pub fn of(cp: u21) u2 {
    if (cp < 0x300) return 1; // fast path: ASCII and Latin
    if (inTable(&zero_width, cp)) return 0;
    if (inTable(&double_width, cp)) return 2;
    return 1;
}

fn checkSorted(table: []const Range) !void {
    for (table, 0..) |e, i| {
        try std.testing.expect(e.lo <= e.hi);
        if (i > 0) try std.testing.expect(table[i - 1].hi < e.lo);
    }
}

test "width tables are sorted and disjoint" {
    try checkSorted(&zero_width);
    try checkSorted(&double_width);
    for (zero_width) |z| {
        try std.testing.expect(!inTable(&double_width, z.lo));
        try std.testing.expect(!inTable(&double_width, z.hi));
    }
}

